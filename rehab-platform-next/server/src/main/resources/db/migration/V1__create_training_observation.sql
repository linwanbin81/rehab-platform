CREATE TABLE training_observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_code VARCHAR(40) NOT NULL,
    training_side VARCHAR(5) NOT NULL CHECK (training_side IN ('LEFT', 'RIGHT')),
    evaluation_mode VARCHAR(7) NOT NULL CHECK (evaluation_mode IN ('observe', 'target')),
    target_json CLOB,
    frames_json CLOB NOT NULL,
    rules_version VARCHAR(32) NOT NULL,
    valid_frames INTEGER NOT NULL CHECK (valid_frames >= 0),
    total_frames INTEGER NOT NULL CHECK (total_frames >= valid_frames),
    interrupted_attempts INTEGER NOT NULL CHECK (interrupted_attempts >= 0),
    duration_seconds DOUBLE PRECISION NOT NULL CHECK (duration_seconds >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE observation_repetition (
    observation_id BIGINT NOT NULL REFERENCES training_observation(id) ON DELETE CASCADE,
    repetition_number INTEGER NOT NULL CHECK (repetition_number > 0),
    peak_degrees DOUBLE PRECISION NOT NULL,
    exercise_seconds DOUBLE PRECISION NOT NULL,
    hold_seconds DOUBLE PRECISION NOT NULL,
    start_seconds DOUBLE PRECISION NOT NULL,
    end_seconds DOUBLE PRECISION NOT NULL,
    amplitude_met BOOLEAN,
    tempo_met BOOLEAN,
    hold_met BOOLEAN,
    PRIMARY KEY (observation_id, repetition_number)
);
