CREATE TABLE workspace_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    display_name VARCHAR(100) NOT NULL,
    account_role VARCHAR(7) NOT NULL CHECK (account_role IN ('ADMIN', 'GUIDE', 'TRAINEE')),
    password_salt CHAR(32) NOT NULL,
    password_hash CHAR(64) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE workspace_login_session (
    token_digest CHAR(64) PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES workspace_account(id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_workspace_login_account ON workspace_login_session(account_id);

CREATE TABLE workspace_trainee (
    account_id BIGINT PRIMARY KEY REFERENCES workspace_account(id),
    guide_id BIGINT REFERENCES workspace_account(id)
);

CREATE INDEX ix_workspace_trainee_guide ON workspace_trainee(guide_id);

CREATE TABLE workspace_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainee_id BIGINT NOT NULL REFERENCES workspace_trainee(account_id),
    guide_id BIGINT REFERENCES workspace_account(id),
    author_id BIGINT NOT NULL REFERENCES workspace_account(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE workspace_baseline (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainee_id BIGINT NOT NULL REFERENCES workspace_trainee(account_id),
    author_id BIGINT NOT NULL REFERENCES workspace_account(id),
    training_side VARCHAR(5) NOT NULL CHECK (training_side IN ('LEFT', 'RIGHT')),
    note VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_workspace_baseline_trainee ON workspace_baseline(trainee_id, id);

CREATE TABLE workspace_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    trainee_id BIGINT NOT NULL REFERENCES workspace_trainee(account_id),
    author_id BIGINT NOT NULL REFERENCES workspace_account(id),
    baseline_id BIGINT REFERENCES workspace_baseline(id),
    scheduled_date DATE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_workspace_plan_trainee ON workspace_plan(trainee_id, scheduled_date, id);

CREATE TABLE workspace_plan_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES workspace_plan(id),
    item_number INTEGER NOT NULL CHECK (item_number > 0),
    exercise_code VARCHAR(40) NOT NULL,
    training_side VARCHAR(5) NOT NULL CHECK (training_side IN ('LEFT', 'RIGHT')),
    evaluation_mode VARCHAR(7) NOT NULL CHECK (evaluation_mode IN ('observe', 'target')),
    sets INTEGER NOT NULL CHECK (sets BETWEEN 1 AND 20),
    reps INTEGER NOT NULL CHECK (reps BETWEEN 1 AND 100),
    rules_version VARCHAR(32) NOT NULL,
    angle_min DOUBLE PRECISION,
    angle_max DOUBLE PRECISION,
    cycle_min DOUBLE PRECISION,
    cycle_max DOUBLE PRECISION,
    hold_seconds DOUBLE PRECISION,
    CONSTRAINT uq_workspace_plan_item_order UNIQUE (plan_id, item_number),
    CONSTRAINT ck_workspace_plan_item_target CHECK (
        (evaluation_mode = 'observe' AND angle_min IS NULL AND angle_max IS NULL
            AND cycle_min IS NULL AND cycle_max IS NULL AND hold_seconds IS NULL)
        OR (evaluation_mode = 'target' AND angle_min IS NOT NULL AND angle_max IS NOT NULL
            AND cycle_min IS NOT NULL AND cycle_max IS NOT NULL AND hold_seconds IS NOT NULL)
    )
);

