CREATE TABLE observation_event_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id BIGINT NOT NULL,
    repetition_number INTEGER NOT NULL,
    metric VARCHAR(9) NOT NULL CHECK (metric IN ('amplitude', 'tempo', 'hold')),
    decision VARCHAR(9) NOT NULL CHECK (decision IN ('CONFIRMED', 'DISMISSED')),
    note VARCHAR(2000) NOT NULL,
    author_id BIGINT NOT NULL REFERENCES workspace_account(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (observation_id, repetition_number)
        REFERENCES observation_repetition(observation_id, repetition_number) ON DELETE CASCADE
);

CREATE INDEX idx_observation_event_review ON observation_event_review(observation_id, repetition_number, metric, id);

CREATE TABLE observation_report_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id BIGINT NOT NULL REFERENCES training_observation(id) ON DELETE CASCADE,
    review_status VARCHAR(12) NOT NULL CHECK (review_status IN ('IN_REVIEW', 'FINALIZED')),
    note VARCHAR(2000) NOT NULL,
    author_id BIGINT NOT NULL REFERENCES workspace_account(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_observation_report_review ON observation_report_review(observation_id, id);
